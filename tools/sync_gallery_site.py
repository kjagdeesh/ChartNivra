"""Export Gallery card metadata and displayed source snippets for the static site."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / 'samples/ChartNivra.Gallery/Pages'
keys = ['line', 'bar', 'area', 'scatter', 'spline', 'range', 'waterfall',
        'pie', 'donut', 'sunburst', 'radar', 'heatmap', 'treemap', 'candlestick',
        'technical', 'histogram', 'boxplot', 'gauge', 'lineargauge', 'funnel',
        '3dbar', '3dsurface', '3dscatter', 'streaming', 'studio3d',
        'annotations', 'realtime', 'multiseries']
home = (PAGES / 'HomePage.cs').read_text(encoding='utf-8-sig')
pattern = r'\("([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*(null|"[^"]+"),\s*ChartThumbnailKind\.(\w+),\s*\[([^\]]*)\]\)'
cards = re.findall(pattern, home)
if len(cards) != len(keys):
    raise SystemExit(f'Expected {len(keys)} Gallery cards, found {len(cards)}; update the site key mapping.')

host = (ROOT / 'samples/ChartNivra.Gallery/Controls/SampleXaml.cs').read_text(encoding='utf-8-sig')
xaml = re.search(r'Host\s*=\s*"""\s*\n(.*?)\n"""', host, re.S).group(1)
catalog = (PAGES / 'ChartCatalogPreviewPage.cs').read_text(encoding='utf-8-sig')
catalog = catalog[catalog.index('private string CreateCsharpSource()'):catalog.index('private void UpdateLayout(')]
literal = r'"(?:\\.|[^"\\])*"'
catalog_snippets = {}
for kind, string in re.findall(r'if \(_kind == ChartThumbnailKind\.(\w+)\) return (' + literal + r');', catalog):
    catalog_snippets[kind] = json.loads(string)
strings = [json.loads(s) for s in re.findall(r'[?:]\s*(' + literal + r')', catalog)]
for key, marker in [('scatter', 'var model = new BubbleSeriesModel'),
                    ('3dscatter', 'var model = new ScatterChart3DModel'),
                    ('3dsurface', 'var model = new SurfaceChart3DModel'),
                    ('3dbar', 'var model = new ColumnChart3DModel')]:
    matches = [s for s in strings if s.startswith(marker)]
    if not matches:
        raise SystemExit(f'Could not extract {key} from the Gallery catalog.')
    catalog_snippets[key] = matches[0]

page_by_route = {'line': 'LineChartPage.cs', 'pie': 'PieChartPage.cs',
                 'donut': 'DonutChartPage.cs', 'radar': 'RadarChartPage.cs',
                 'heatmap': 'HeatmapPage.cs', 'candlestick': 'CandlestickPage.cs',
                 'boxplot': 'BoxPlotPage.cs', 'gauge': 'GaugePage.cs',
                 'annotations': 'AnnotationsPage.cs', 'realtime': 'RealTimePage.cs',
                 'multiseries': 'MultiSeriesPage.cs'}
studio_by_route = {'demo-streaming': 'Demos/StreamingDemoPage.cs',
                   'demo-3d': 'Demos/ThreeDDemoPage.cs'}
data = {}
for key, (title, category, description, route, kind, tags) in zip(keys, cards):
    route = route.strip('"')
    if route in page_by_route:
        source = (PAGES / page_by_route[route]).read_text(encoding='utf-8-sig')
        match = re.search(r'private const string Code\s*=\s*"""\s*\n(.*?)\n"""', source, re.S)
        if not match:
            raise SystemExit(f'No displayed C# snippet found for {route}.')
        csharp = match.group(1)
        sample_xaml = xaml
    elif route in studio_by_route:
        csharp = (PAGES / studio_by_route[route]).read_text(encoding='utf-8-sig')
        sample_xaml = None  # These Gallery studio pages are implemented in C#.
    else:
        csharp = catalog_snippets.get(key) or catalog_snippets.get(kind)
        if csharp is None:
            raise SystemExit(f'No Gallery catalog snippet found for {key} ({kind}).')
        sample_xaml = xaml
    data[key] = {'title': title, 'category': category.lower(), 'desc': description,
                 'tags': re.findall(r'"([^"]+)"', tags), 'xaml': sample_xaml, 'csharp': csharp}

output = ROOT / 'docs/site/assets/js/gallery-data.js'
output.write_text('// Generated by tools/sync_gallery_site.py from the Gallery source.\n'
                  'const galleryData = ' + json.dumps(data, indent=2, ensure_ascii=False) + ';\n', encoding='utf-8')
print(f'Exported {len(data)} Gallery cards to {output.relative_to(ROOT)}')
